const img = (id, w = 800, h = 1000) =>
  `https://images.unsplash.com/${id}?auto=format&fit=crop&w=${w}&h=${h}&q=80`

const buildGallery = (main) => {
  const suffix = main.split('?')[0]
  return [
    main,
    `${suffix}?auto=format&fit=crop&w=900&h=1200&q=80`,
    `${suffix}?auto=format&fit=crop&w=900&h=900&q=80`,
    `${suffix}?auto=format&fit=crop&w=900&h=1100&q=80`,
  ]
}

